"""Render docs/differences.md and docs/field-coverage*.md from the difference rule
catalogue's metadata and each plugin's generator FIELD_COVERAGE.

    uv run python scripts/gen_differences_doc.py

Walks `registry.PLUGINS`; a plugin whose `generate_gcp` module declares no
`FIELD_COVERAGE` is skipped. The network plugin keeps its historical, unsuffixed
`docs/field-coverage.md`; every other plugin gets `docs/field-coverage-<family>.md`.

`tests/differences/test_docs.py` and each family's `test_field_coverage.py` fail if
the committed files differ from this output."""

from __future__ import annotations

import importlib
import sys
from itertools import groupby
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from easymigrate.core.registry import PLUGINS  # noqa: E402
from easymigrate.differences.engine import catalogue  # noqa: E402

OUTPUT = ROOT / "docs" / "differences.md"

# Kept for backward compatibility: the network doc's historical, unsuffixed path.
FIELD_COVERAGE_OUTPUT = ROOT / "docs" / "field-coverage.md"


def field_coverage_output_path(family: str) -> Path:
    if family == "network":
        return FIELD_COVERAGE_OUTPUT
    return ROOT / "docs" / f"field-coverage-{family}.md"


def _field_coverage_for(family: str) -> dict[str, dict[str, str]] | None:
    module = importlib.import_module(f"easymigrate.plugins.{family}.generate_gcp")
    return getattr(module, "FIELD_COVERAGE", None)


def render() -> str:
    lines = [
        "# AWS → GCP differences",
        "",
        "Generated by `scripts/gen_differences_doc.py` from the rule catalogue. Do not edit by "
        "hand.",
        "",
    ]
    for family, rules in groupby(catalogue(), key=lambda r: r.family):
        lines.append(f"## {family.title()} rules")
        lines.append("")
        for rule in rules:
            lines.append(f"### {rule.title} (`{rule.id}`)")
            lines.append("")
            lines.append(rule.impact)
            lines.append("")
            lines.append("| Strategy | Title | Effect | Risk | Manual | Default |")
            lines.append("|---|---|---|---|---|---|")
            for strategy in rule.strategies:
                default = "yes" if strategy.id == rule.default else ""
                manual = "yes" if strategy.manual else ""
                lines.append(
                    f"| `{strategy.id}` | {strategy.title} | {strategy.effect} | {strategy.risk} "
                    f"| {manual} | {default} |"
                )
            lines.append("")
            if rule.param_docs:
                lines.append("Params:")
                lines.append("")
                for name in sorted(rule.param_docs):
                    lines.append(f"- `{name}`: {rule.param_docs[name]}")
                lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def render_field_coverage(family: str = "network") -> str:
    field_coverage = _field_coverage_for(family)
    if field_coverage is None:
        raise ValueError(f"plugin {family!r} has no generate_gcp.FIELD_COVERAGE")

    lines = [
        f"# {family.title()} generator field coverage",
        "",
        "Generated by `scripts/gen_differences_doc.py` from "
        f"`easymigrate.plugins.{family}.generate_gcp.FIELD_COVERAGE`. Do not edit by hand.",
        "",
        f"Every IR field the {family} generator could touch is declared here, so an IR field "
        "added without declaring how the generator handles it fails CI (no silent mapping).",
        "",
    ]
    for kind in sorted(field_coverage):
        lines.append(f"## `{kind}`")
        lines.append("")
        lines.append("| Field | Declaration |")
        lines.append("|---|---|")
        for field in sorted(field_coverage[kind]):
            lines.append(f"| `{field}` | {field_coverage[kind][field]} |")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def main() -> None:
    OUTPUT.write_text(render(), encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)}")

    for plugin in PLUGINS:
        if _field_coverage_for(plugin.name) is None:
            continue
        output_path = field_coverage_output_path(plugin.name)
        output_path.write_text(render_field_coverage(plugin.name), encoding="utf-8")
        print(f"wrote {output_path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
