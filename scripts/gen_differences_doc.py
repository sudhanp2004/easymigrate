"""Render docs/differences.md and docs/field-coverage.md from the difference rule
catalogue's metadata and the network generator's FIELD_COVERAGE.

    uv run python scripts/gen_differences_doc.py

`tests/differences/test_docs.py` and `tests/plugins/network/test_field_coverage.py`
fail if the committed files differ from this output."""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from easymigrate.differences.engine import catalogue  # noqa: E402
from easymigrate.plugins.network.generate_gcp import FIELD_COVERAGE  # noqa: E402

OUTPUT = ROOT / "docs" / "differences.md"
FIELD_COVERAGE_OUTPUT = ROOT / "docs" / "field-coverage.md"


def render() -> str:
    lines = [
        "# AWS → GCP differences",
        "",
        "Generated by `scripts/gen_differences_doc.py` from the rule catalogue. Do not edit by "
        "hand.",
        "",
    ]
    for rule in catalogue():
        lines.append(f"## {rule.title} (`{rule.id}`)")
        lines.append("")
        lines.append(rule.impact)
        lines.append("")
        lines.append("| Strategy | Title | Effect | Risk | Manual | Default |")
        lines.append("|---|---|---|---|---|---|")
        for strategy in rule.strategies:
            default = "yes" if strategy.id == rule.default else ""
            manual = "yes" if strategy.manual else ""
            lines.append(
                f"| `{strategy.id}` | {strategy.title} | {strategy.effect} | {strategy.risk} "
                f"| {manual} | {default} |"
            )
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def render_field_coverage() -> str:
    lines = [
        "# Network generator field coverage",
        "",
        "Generated by `scripts/gen_differences_doc.py` from "
        "`easymigrate.plugins.network.generate_gcp.FIELD_COVERAGE`. Do not edit by hand.",
        "",
        "Every IR field the network generator could touch is declared here, so an IR field "
        "added without declaring how the generator handles it fails CI (no silent mapping).",
        "",
    ]
    for kind in sorted(FIELD_COVERAGE):
        lines.append(f"## `{kind}`")
        lines.append("")
        lines.append("| Field | Declaration |")
        lines.append("|---|---|")
        for field in sorted(FIELD_COVERAGE[kind]):
            lines.append(f"| `{field}` | {FIELD_COVERAGE[kind][field]} |")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def main() -> None:
    OUTPUT.write_text(render(), encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    FIELD_COVERAGE_OUTPUT.write_text(render_field_coverage(), encoding="utf-8")
    print(f"wrote {FIELD_COVERAGE_OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
