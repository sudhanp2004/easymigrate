"""Static terraform/*.tf boilerplate the `plan` step generates alongside plugin output
(spec §5.2 "Output files", plan 4 B2 step 6)."""

from __future__ import annotations

from easymigrate.providers.gcp.boilerplate import (
    render_backend_tf,
    render_providers_tf,
    render_tfvars,
    render_variables_tf,
)

_HEADER = "Generated by EasyMigrate 1.2.3. Do not edit by hand; re-run easymigrate plan."


def test_providers_tf_pins_google_provider():
    out = render_providers_tf("1.2.3")
    assert _HEADER in out
    assert 'source  = "hashicorp/google"' in out
    assert 'version = "~> 8.0"' in out


def test_providers_tf_configures_project_and_region():
    """Regression: without this block every resource fails at plan time with
    "project: required field is not set" — found by the first live run."""
    out = render_providers_tf("1.2.3")

    assert 'provider "google"' in out
    assert "project = var.project" in out
    assert "region  = var.region" in out


def test_backend_tf_declares_gcs_backend():
    out = render_backend_tf("1.2.3")
    assert _HEADER in out
    assert 'backend "gcs"' in out


def test_variables_tf_declares_project_and_region():
    out = render_variables_tf("1.2.3")
    assert _HEADER in out
    assert 'variable "project"' in out
    assert 'variable "region"' in out


def test_tfvars_has_escaped_project_and_region_values():
    out = render_tfvars("my-project", "us-east4", "1.2.3")
    assert _HEADER in out
    assert 'project = "my-project"' in out
    assert 'region  = "us-east4"' in out


def test_tfvars_escapes_quotes_in_values():
    out = render_tfvars('my"project', "us-east4", "1.2.3")
    assert 'my\\"project' in out
