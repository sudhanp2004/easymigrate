_DEFAULT_DISK_TYPE = "pd-balanced"


def _slug(ir_id: str) -> str:
    return ir_id.split(":", 1)[1]


class _Names:
    def __init__(self) -> None:
        self.tf = TfLabelAllocator()
        self.gcp = GcpNameAllocator()
        self.label: dict[str, str] = {}
        self.name: dict[str, str] = {}

    def allocate(self, resource_type: str, ir_id: str) -> tuple[str, str, bool]:
        label = self.tf.allocate(resource_type, ir_id)
        gcp, _ = self.gcp.allocate(resource_type, _slug(ir_id))
        self.label[ir_id] = label
        self.name[ir_id] = gcp
        return label, gcp, False


def _live(resolved: IRDocument, kind) -> list:
    return sorted(
        (obj for obj in resolved.of_kind(kind) if obj.excluded is None),
        key=lambda obj: obj.id,
    )


def _header_lines(obj, decided_by: dict[str, str]) -> list[str]:
    lines = [f"from AWS {obj.source.type} {obj.source.id} ({obj.name})"]
    for ref in obj.resolution:
        lines.append(f"decision {ref.key} → {ref.strategy} ({decided_by.get(ref.key, 'default')})")
    return lines


def generate(resolved: IRDocument, ctx: GenerateContext) -> HclFile:
    file = HclFile(header=[_HEADER.format(version=ctx.version)])

    instances = [
        instance for instance in _live(resolved, ComputeInstance) if not instance.eks_cluster
    ]
    if not instances:
        return file

    disks = {disk.id: disk for disk in resolved.of_kind(Disk)}
    subnet_labels = _subnet_labels(resolved)
    tags, _ = policy_network_tags(resolved.of_kind(FirewallPolicy))
    live_policies = {policy.id for policy in _live(resolved, FirewallPolicy)}

    names = _Names()
    for instance in instances:
        names.allocate("google_compute_instance", instance.id)
    for disk in _live(resolved, Disk):
        if not disk.boot and not disk.instance_store:
            names.allocate("google_compute_disk", disk.id)

    for disk in _live(resolved, Disk):
        if disk.boot or disk.instance_store:
            continue
        _generate_disk(file, names, disk, ctx)

    for instance in instances:
        _generate_instance(file, names, instance, disks, subnet_labels, tags, live_policies, ctx)
    return file


def _subnet_labels(resolved: IRDocument) -> dict[str, str]:
    """The Terraform labels the network generator gave each subnet, recomputed the same way."""
    allocator = TfLabelAllocator()
    labels: dict[str, str] = {}
    for subnet in sorted(resolved.of_kind(Subnet), key=lambda s: s.id):
        labels[subnet.id] = allocator.allocate("google_compute_subnetwork", subnet.id)
    return labels


def _generate_disk(file: HclFile, names: _Names, disk: Disk, ctx: GenerateContext) -> None:
    block = file.block("resource", "google_compute_disk", names.label[disk.id])
    block.comment("\n".join(_header_lines(disk, ctx.decided_by)))
    block.attr("name", names.name[disk.id])
    block.attr("type", disk.target_hints.get("disk_type", _DEFAULT_DISK_TYPE))
    block.attr("zone", Ref(f'"${{var.region}}-{_zone_letter_for_disk(disk)}"'))
    if disk.size_gib:
        block.attr("size", disk.size_gib)
    if disk.labels:
        block.attr("labels", dict(sorted(disk.labels.items())))


def _zone_letter_for_disk(disk: Disk) -> str:
    return disk.target_hints.get("zone_letter", "a")


def _require(obj, key: str):
    value = obj.target_hints.get(key)
    if value is None:
        raise GenerationError(
            f"{obj.id} has no {key!r} target hint; a VM-* difference rule did not run"
        )
    return value


def _generate_instance(
    file: HclFile,
    names: _Names,
    instance: ComputeInstance,
    disks: dict[str, Disk],
    subnet_labels: dict[str, str],
    tags: dict[str, str],
    live_policies: set[str],
    ctx: GenerateContext,
) -> None:
    machine_type = _require(instance, "machine_type")
    boot_image = _require(instance, "boot_image")
    zone_letter = _require(instance, "zone_letter")

    block = file.block("resource", "google_compute_instance", names.label[instance.id])
    block.comment("\n".join(_header_lines(instance, ctx.decided_by)))
    block.attr("name", names.name[instance.id])
    block.attr("machine_type", machine_type)
    block.attr("zone", Ref(f'"${{var.region}}-{zone_letter}"'))

    boot = _boot_disk(instance, disks)
    boot_block = block.block("boot_disk")
    params = boot_block.block("initialize_params")
    params.attr("image", f"{boot_image['project']}/{boot_image['family']}")
    # VM-BOOT-DISK-MINIMUM raises this when the source root volume is smaller than the stock
    # image needs; GCP refuses a boot disk below the image's minimum.
    size = instance.target_hints.get("boot_disk_size_gib") or boot.size_gib
    if size:
        params.attr("size", size)
    params.attr("type", boot.target_hints.get("disk_type", _DEFAULT_DISK_TYPE))

    for disk_id in instance.disks:
        disk = disks[disk_id]
        if disk.boot or disk.excluded is not None:
            continue
        if disk.instance_store:
            scratch = block.block("scratch_disk")
            scratch.attr("interface", "NVME")
            continue
        attached = block.block("attached_disk")
        attached.attr("source", Ref(f"google_compute_disk.{names.label[disk_id]}.id"))

    interface = block.block("network_interface")
    interface.attr(
        "subnetwork", Ref(f"google_compute_subnetwork.{subnet_labels[instance.subnet]}.id")
    )
    if instance.target_hints.get("external", "none") != "none":
        interface.block("access_config")

    instance_tags = sorted(
        tags[policy_id] for policy_id in instance.firewall_policies if policy_id in live_policies
    )
    if instance_tags:
        block.attr("tags", instance_tags)
    elif instance.firewall_policies:
        ctx.info(
            "GEN-NO-TAGS",
            f"{instance.id} has no network tags: every security group protecting it was "
            "removed by a decision, so no migrated firewall rule applies to it.",
            subject=instance.id,
        )

    if instance.labels:
        block.attr("labels", dict(sorted(instance.labels.items())))
    desired_status = instance.target_hints.get("desired_status")
    if desired_status:
        block.attr("desired_status", desired_status)


def _boot_disk(instance: ComputeInstance, disks: dict[str, Disk]) -> Disk:
    for disk_id in instance.disks:
        disk = disks.get(disk_id)
        if disk is not None and disk.boot:
            if disk.excluded is not None:
                raise GenerationError(
                    f"{instance.id} has no boot disk: {disk_id} was excluded, which would "
                    "leave an instance that cannot start"
                )
            return disk
    raise GenerationError(f"{instance.id} has no boot disk")
