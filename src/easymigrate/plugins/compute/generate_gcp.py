"""Compute → GCP Terraform generation (spec 4 §6).

Reads only resolved IR and `target_hints`, and skips objects with `excluded` set. Contains no
difference logic: anything this module cannot represent — a missing machine type, boot image or
zone letter, or a boot disk that was excluded — means a difference rule failed to run, and
`GenerationError` guards that contract.
"""

