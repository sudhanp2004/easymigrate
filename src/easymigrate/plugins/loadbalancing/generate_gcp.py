# Google front ends and health checkers reach backends from these ranges.
_PROXY_HEALTH_RANGES = ["130.211.0.0/22", "35.191.0.0/16"]
_PASSTHROUGH_EXTERNAL_HEALTH_RANGES = ["209.85.152.0/22", "209.85.204.0/22", "35.191.0.0/16"]
_REDIRECT_CODES = {
    "HTTP_301": "MOVED_PERMANENTLY_DEFAULT",
    "HTTP_302": "FOUND",
}
_ARMOR_RANGES_PER_RULE = 10


def _name(*parts: str) -> str:
    raw = "-".join(p for p in parts if p).lower()
    cleaned = re.sub(r"[^a-z0-9-]", "-", raw)
    cleaned = re.sub(r"-+", "-", cleaned).strip("-")
    if not cleaned or not cleaned[0].isalpha():
        cleaned = f"lb-{cleaned}"
    return cleaned[:63].rstrip("-")


def _slug(ir_id: str) -> str:
    return ir_id.split(":", 1)[1]


def _require(obj, key: str):
    value = obj.target_hints.get(key)
    if value is None:
        raise GenerationError(
            f"{obj.id} has no {key!r} target hint; an LB-* difference rule did not run"
        )
    return value


def _header_lines(obj, decided_by: dict[str, str]) -> list[str]:
    lines = [f"from AWS {obj.source.type} {obj.name}"]
    for ref in obj.resolution:
        lines.append(f"decision {ref.key} → {ref.strategy} ({decided_by.get(ref.key, 'default')})")
    return lines


@dataclass
class _Context:
    resolved: IRDocument
    ctx: GenerateContext
    labels: TfLabelAllocator = field(default_factory=TfLabelAllocator)
    tgs: dict[str, TargetGroup] = field(default_factory=dict)
    # target group id -> Terraform expressions of its backend instance groups
    backends: dict[str, list[str]] = field(default_factory=dict)
    # target group id -> network tags of its backend instances
    tags: dict[str, list[str]] = field(default_factory=dict)
    network_labels: dict[str, str] = field(default_factory=dict)
    subnet_labels: dict[str, str] = field(default_factory=dict)
    proxy_subnets: dict[str, str] = field(default_factory=dict)  # network id -> TF label


def generate(resolved: IRDocument, ctx: GenerateContext) -> HclFile:
    file = HclFile(header=[_HEADER.format(version=ctx.version)])
    lbs = sorted(
        (lb for lb in resolved.of_kind(LoadBalancer) if lb.excluded is None), key=lambda o: o.id
    )
    if not lbs:
        return file
    state = _Context(
        resolved=resolved,
        ctx=ctx,
        tgs={tg.id: tg for tg in resolved.of_kind(TargetGroup) if tg.excluded is None},
        network_labels=network_tf_labels(resolved),
        subnet_labels=subnet_tf_labels(resolved),
    )
    _instance_groups(file, state, lbs)
    for lb in lbs:
        shape = _require(lb, "shape")
        if shape == "global_external_alb":
            _alb(file, state, lb, regional=False)
        elif shape == "regional_internal_alb":
            _alb(file, state, lb, regional=True)
        else:
            _passthrough(file, state, lb, internal=shape == "internal_passthrough_nlb")
    return file


def _used_target_groups(lb: LoadBalancer, tgs: dict[str, TargetGroup]) -> list[str]:
    used = {
        t.target_group
        for listener in lb.listeners
        for action in [listener.default_action, *(r.action for r in listener.rules)]
        for t in action.target_groups
        if t.target_group in tgs
    }
    used |= {f for f in lb.target_hints.get("default_fallbacks", {}).values() if f in tgs}
    return sorted(used)


def _instance_groups(file: HclFile, state: _Context, lbs: list[LoadBalancer]) -> None:
    """One unmanaged group per (network, zone) holding every targeted standalone instance: GCP
    lets an instance belong to only one load-balanced group (spec 7 D5)."""
    resolved, ctx = state.resolved, state.ctx
    instance_labels = instance_tf_labels(resolved)
    group_refs = group_tf_refs(resolved)
    instances = {i.id: i for i in resolved.of_kind(ComputeInstance)}
    subnets = {s.id: s for s in resolved.of_kind(Subnet)}
    groups = {g.id: g for g in resolved.of_kind(InstanceGroup)}
    templates = {t.id: t for t in resolved.of_kind(InstanceTemplate)}
    policy_tags, _ = policy_network_tags(resolved.of_kind(FirewallPolicy))
    live_policies = {p.id for p in resolved.of_kind(FirewallPolicy) if p.excluded is None}

    used = sorted({tg for lb in lbs for tg in _used_target_groups(lb, state.tgs)})
    members: dict[tuple[str, str], set[str]] = {}
    ports: dict[tuple[str, str], dict[str, int]] = {}
    tg_zones: dict[str, set[tuple[str, str]]] = {}
    for tg_id in used:
        tg = state.tgs[tg_id]
        named = tg.target_hints.get("named_port")
        tags: set[str] = set()
        for instance_id in tg.instances:
            instance = instances.get(instance_id)
            if instance_id not in instance_labels or instance is None:
                ctx.info(
                    "GEN-LB-TARGET-SKIPPED",
                    f"{tg_id} targets {instance_id}, which is not generated; it gets no traffic.",
                    subject=tg_id,
                )
                continue
            letter = instance.target_hints.get("zone_letter")
            if letter is None:
                raise GenerationError(f"{instance_id} has no zone; VM-ZONE-MAPPING did not run")
            suffix, _ = zone_suffix(ctx.region, letter)
            key = (subnets[instance.subnet].network, suffix)
            members.setdefault(key, set()).add(instance_id)
            if named:
                ports.setdefault(key, {})[named["name"]] = named["port"]
            tg_zones.setdefault(tg_id, set()).add(key)
            tags |= {policy_tags[p] for p in instance.firewall_policies if p in live_policies}
        refs: list[str] = []
        for group_id in tg.groups:
            if group_id not in group_refs:
                continue
            refs.append(group_refs[group_id])
            template = templates.get(groups[group_id].template)
            if template is not None:
                tags |= {policy_tags[p] for p in template.firewall_policies if p in live_policies}
        state.backends[tg_id] = refs
        state.tags[tg_id] = sorted(tags)

    group_labels: dict[tuple[str, str], str] = {}
    for key in sorted(members):
        network, suffix = key
        label = state.labels.allocate(
            "google_compute_instance_group", f"lb_{_slug(network)}_{suffix}"
        )
        group_labels[key] = label
        block = file.block("resource", "google_compute_instance_group", label)
        block.comment("migrated instances behind load balancers, one group per zone (LB-BACKENDS)")
        block.attr("name", _name("lb", _slug(network), suffix))
        block.attr("zone", Ref(f'"${{var.region}}-{suffix}"'))
        block.attr("network", Ref(f"google_compute_network.{state.network_labels[network]}.id"))
        block.attr(
            "instances",
            [
                Ref(f"google_compute_instance.{instance_labels[i]}.self_link")
                for i in sorted(members[key])
            ],
        )
        for name, port in sorted(ports.get(key, {}).items()):
            named = block.block("named_port")
            named.attr("name", name)
            named.attr("port", port)
    for tg_id, keys in tg_zones.items():
        state.backends[tg_id] = [
            *(f"google_compute_instance_group.{group_labels[k]}.id" for k in sorted(keys)),
            *state.backends.get(tg_id, []),
        ]


def _health_check(
    file: HclFile, state: _Context, lb_label: str, tg: TargetGroup, regional: bool
) -> str:
    check = _require(tg, "health_check")
    kind = "google_compute_region_health_check" if regional else "google_compute_health_check"
    label = state.labels.allocate(kind, f"{lb_label}_{_slug(tg.id)}")
    block = file.block("resource", kind, label)
    block.attr("name", _name(lb_label, _slug(tg.id), "hc"))
    if regional:
        block.attr("region", Ref("var.region"))
    block.attr("check_interval_sec", check["check_interval_sec"])
    block.attr("timeout_sec", check["timeout_sec"])
    block.attr("healthy_threshold", check["healthy_threshold"])
    block.attr("unhealthy_threshold", check["unhealthy_threshold"])
    protocol = check["protocol"].lower()
    inner = block.block(f"{protocol}_health_check")
    inner.attr("port", check["port"])
    if check.get("request_path") and protocol != "tcp":
        inner.attr("request_path", check["request_path"])
    return f"{kind}.{label}.id"


def _backend_service(
    file: HclFile,
    state: _Context,
    lb: LoadBalancer,
    lb_label: str,
    tg: TargetGroup,
    *,
    scheme: str,
    regional: bool,
    security_policy: str | None = None,
) -> str:
    health = _health_check(file, state, lb_label, tg, regional)
    kind = "google_compute_region_backend_service" if regional else "google_compute_backend_service"
    label = state.labels.allocate(kind, f"{lb_label}_{_slug(tg.id)}")
    block = file.block("resource", kind, label)
    block.comment("\n".join(_header_lines(tg, state.ctx.decided_by)))
    block.attr("name", _name(lb_label, _slug(tg.id)))
    if regional:
        block.attr("region", Ref("var.region"))
    block.attr("load_balancing_scheme", scheme)
    passthrough = scheme in {"EXTERNAL", "INTERNAL"}
    protocol = tg.protocol.upper()
    if passthrough:
        block.attr("protocol", "UDP" if protocol == "UDP" else "TCP")
    else:
        block.attr("protocol", "HTTPS" if protocol == "HTTPS" else "HTTP")
        named = tg.target_hints.get("named_port")
        if named:
            block.attr("port_name", named["name"])
        if lb.idle_timeout:
            block.attr("timeout_sec", lb.idle_timeout)
    block.attr("health_checks", [Ref(health)])
    if tg.deregistration_delay is not None:
        block.attr("connection_draining_timeout_sec", tg.deregistration_delay)
    affinity = tg.target_hints.get("affinity")
    if affinity and not passthrough:
        block.attr("session_affinity", affinity["mode"])
        if affinity["mode"] == "GENERATED_COOKIE" and affinity.get("ttl"):
            block.attr("affinity_cookie_ttl_sec", affinity["ttl"])
        if affinity["mode"] == "HTTP_COOKIE":
            block.attr("locality_lb_policy", "RING_HASH")
            cookie = block.block("consistent_hash").block("http_cookie")
            cookie.attr("name", affinity.get("cookie") or "session")
            if affinity.get("ttl"):
                cookie.block("ttl").attr("seconds", affinity["ttl"])
    if security_policy:
        block.attr("security_policy", Ref(security_policy))
    if lb.target_hints.get("logging"):
        log = block.block("log_config")
        log.attr("enable", True)
        log.attr("sample_rate", 1.0)
    backends = state.backends.get(tg.id, [])
    if not backends:
        state.ctx.info(
            "GEN-LB-NO-BACKENDS",
            f"{tg.id} has no migrated backends; its backend service is created empty.",
            subject=tg.id,
        )
    for ref in backends:
        backend = block.block("backend")
        backend.attr("group", Ref(ref))
        if passthrough:
            backend.attr("balancing_mode", "CONNECTION")
        else:
            backend.attr("balancing_mode", "UTILIZATION")
            backend.attr("capacity_scaler", 1.0)
    return f"{kind}.{label}.id"


def _dropped(lb: LoadBalancer, port: int) -> set[int]:
    return {d["priority"] for d in lb.target_hints.get("dropped_rules", []) if d["port"] == port}


def _redirect(block: Block, action: Action) -> None:
    redirect = action.redirect
    if redirect.protocol == "HTTPS":
        block.attr("https_redirect", True)
    if redirect.host and redirect.host != "#{host}":
        block.attr("host_redirect", redirect.host)
    if redirect.path and redirect.path != "/#{path}":
        block.attr("path_redirect", redirect.path)
    block.attr("redirect_response_code", _REDIRECT_CODES.get(redirect.status, "FOUND"))
    block.attr("strip_query", False)


def _route(action: Action, services: dict[str, str]) -> str | None:
    live = [t for t in action.target_groups if t.target_group in services]
    return services[live[0].target_group] if live else None


def _url_map(
    file: HclFile,
    state: _Context,
    lb: LoadBalancer,
    lb_label: str,
    listener: Listener,
    services: dict[str, str],
    regional: bool,
) -> str | None:
    kind = "google_compute_region_url_map" if regional else "google_compute_url_map"
    label = state.labels.allocate(kind, f"{lb_label}_{listener.port}")
    default = listener.default_action
    fallback = lb.target_hints.get("default_fallbacks", {}).get(str(listener.port))
    default_service = services.get(fallback) if fallback else _route(default, services)
    if default.type != "redirect" and default_service is None:
        state.ctx.info(
            "GEN-LB-LISTENER-SKIPPED",
            f"{lb.id} listener {listener.port} has no migrated default target; it is not created.",
            subject=lb.id,
        )
        return None
    block = file.block("resource", kind, label)
    block.attr("name", _name(lb_label, str(listener.port)))
    if regional:
        block.attr("region", Ref("var.region"))
    if default.type == "redirect":
        _redirect(block.block("default_url_redirect"), default)
        return f"{kind}.{label}.id"
    block.attr("default_service", Ref(default_service))

    dropped = _dropped(lb, listener.port)
    by_hosts: dict[tuple[str, ...], list] = {}
    for rule in listener.rules:
        if rule.priority in dropped or rule.action.type not in {"forward", "redirect"}:
            continue
        if rule.action.type == "forward" and _route(rule.action, services) is None:
            continue
        by_hosts.setdefault(tuple(rule.hosts) or ("*",), []).append(rule)
    for index, (hosts, rules) in enumerate(sorted(by_hosts.items())):
        matcher_name = f"m{index}"
        host_rule = block.block("host_rule")
        host_rule.attr("hosts", list(hosts))
        host_rule.attr("path_matcher", matcher_name)
        matcher = block.block("path_matcher")
        matcher.attr("name", matcher_name)
        # A host-only rule sets the matcher's default; otherwise the listener default applies.
        host_only = next((r for r in rules if not r.paths), None)
        if host_only is not None and host_only.action.type == "forward":
            matcher.attr("default_service", Ref(_route(host_only.action, services)))
        else:
            matcher.attr("default_service", Ref(default_service))
        for rule in rules:
            if not rule.paths:
                continue
            path_rule = matcher.block("path_rule")
            path_rule.attr("paths", rule.paths)
            if rule.action.type == "redirect":
                _redirect(path_rule.block("url_redirect"), rule.action)
            else:
                path_rule.attr("service", Ref(_route(rule.action, services)))
    return f"{kind}.{label}.id"


def _security_policy(file: HclFile, state: _Context, lb: LoadBalancer, lb_label: str) -> str | None:
    allow = lb.target_hints.get("allowlist")
    if not allow:
        return None
    label = state.labels.allocate("google_compute_security_policy", lb_label)
    block = file.block("resource", "google_compute_security_policy", label)
    block.comment(f"the source ranges {lb.name}'s security groups admitted (LB-SOURCE-RESTRICTION)")
    block.attr("name", _name(lb_label, "allow"))
    for index in range(0, len(allow), _ARMOR_RANGES_PER_RULE):
        rule = block.block("rule")
        rule.attr("action", "allow")
        rule.attr("priority", 1000 + index)
        match = rule.block("match")
        match.attr("versioned_expr", "SRC_IPS_V1")
        match.block("config").attr("src_ip_ranges", allow[index : index + _ARMOR_RANGES_PER_RULE])
    default = block.block("rule")
    default.attr("action", "deny(403)")
    default.attr("priority", 2147483647)
    match = default.block("match")
    match.attr("versioned_expr", "SRC_IPS_V1")
    match.block("config").attr("src_ip_ranges", ["*"])
    return f"google_compute_security_policy.{label}.id"


def _firewall(
    file: HclFile,
    state: _Context,
    lb_label: str,
    network: str,
    sources: list[str],
    tgs: list[TargetGroup],
    suffix: str,
) -> None:
    ports = sorted(
        {str(tg.port) for tg in tgs if tg.port}
        | {
            str(tg.target_hints["health_check"]["port"])
            for tg in tgs
            if tg.target_hints.get("health_check")
        }
    )
    if not ports:
        return
    tags = sorted({t for tg in tgs for t in state.tags.get(tg.id, [])})
    label = state.labels.allocate("google_compute_firewall", f"{lb_label}_{suffix}")
    block = file.block("resource", "google_compute_firewall", label)
    block.comment("lets the load balancer and its health checks reach the backends")
    block.attr("name", _name(lb_label, suffix))
    block.attr("network", Ref(f"google_compute_network.{state.network_labels[network]}.id"))
    block.attr("direction", "INGRESS")
    block.attr("source_ranges", sources)
    if tags:
        block.attr("target_tags", tags)
    allow = block.block("allow")
    allow.attr("protocol", "tcp")
    allow.attr("ports", ports)


def _network_of(state: _Context, lb: LoadBalancer) -> str:
    network = _require(lb, "network")
    if network not in state.network_labels:
        raise GenerationError(f"{lb.id} is in {network}, which is not generated")
    return network


def _alb(file: HclFile, state: _Context, lb: LoadBalancer, regional: bool) -> None:
    lb_label = state.labels.allocate("load_balancer", lb.id)
    network = _network_of(state, lb)
    skipped = set(lb.target_hints.get("skipped_listeners", []))
    tg_ids = _used_target_groups(lb, state.tgs)
    tgs = [state.tgs[t] for t in tg_ids]
    scheme = "INTERNAL_MANAGED" if regional else "EXTERNAL_MANAGED"

    if regional:
        proxy_label = state.proxy_subnets.get(network)
        if proxy_label is None:
            proxy_label = state.labels.allocate(
                "google_compute_subnetwork", f"{_slug(network)}_proxy"
            )
            state.proxy_subnets[network] = proxy_label
            subnet = file.block("resource", "google_compute_subnetwork", proxy_label)
            subnet.comment("proxy-only subnet for regional internal Application Load Balancers")
            subnet.attr("name", _name(_slug(network), "proxy-only"))
            subnet.attr("ip_cidr_range", _require(lb, "proxy_subnet_cidr"))
            subnet.attr("region", Ref("var.region"))
            subnet.attr(
                "network", Ref(f"google_compute_network.{state.network_labels[network]}.id")
            )
            subnet.attr("purpose", "REGIONAL_MANAGED_PROXY")
            subnet.attr("role", "ACTIVE")
        address_ref = None
    else:
        address = file.block("resource", "google_compute_global_address", lb_label)
        address.comment("\n".join(_header_lines(lb, state.ctx.decided_by)))
        address.attr("name", _name(lb_label, "ip"))
        address_ref = f"google_compute_global_address.{lb_label}.id"

    policy = None if regional else _security_policy(file, state, lb, lb_label)
    services = {
        tg.id: _backend_service(
            file, state, lb, lb_label, tg, scheme=scheme, regional=regional, security_policy=policy
        )
        for tg in tgs
    }
    for listener in lb.listeners:
        if listener.port in skipped:
            continue
        url_map = _url_map(file, state, lb, lb_label, listener, services, regional)
        if url_map is None:
            continue
        https = listener.protocol.upper() == "HTTPS"
        prefix = "google_compute_region_" if regional else "google_compute_"
        proxy_kind = f"{prefix}target_https_proxy" if https else f"{prefix}target_http_proxy"
        proxy_label = state.labels.allocate(proxy_kind, f"{lb_label}_{listener.port}")
        proxy = file.block("resource", proxy_kind, proxy_label)
        proxy.attr("name", _name(lb_label, str(listener.port)))
        if regional:
            proxy.attr("region", Ref("var.region"))
        proxy.attr("url_map", Ref(url_map))
        if https:
            domains = lb.target_hints.get("certificates", {}).get(str(listener.port))
            if not domains:
                raise GenerationError(
                    f"{lb.id} listener {listener.port} has no certificate decision"
                )
            cert_label = state.labels.allocate(
                "google_compute_managed_ssl_certificate", f"{lb_label}_{listener.port}"
            )
            cert = file.block("resource", "google_compute_managed_ssl_certificate", cert_label)
            cert.comment(
                "issued only once these domains resolve to the new address (LB-CERTIFICATES)"
            )
            cert.attr("name", _name(lb_label, str(listener.port), "cert"))
            cert.block("managed").attr("domains", domains)
            proxy.attr(
                "ssl_certificates", [Ref(f"google_compute_managed_ssl_certificate.{cert_label}.id")]
            )
            policy_spec = lb.target_hints.get("ssl_policies", {}).get(str(listener.port))
            if policy_spec:
                ssl_label = state.labels.allocate(
                    "google_compute_ssl_policy", f"{lb_label}_{listener.port}"
                )
                ssl = file.block("resource", "google_compute_ssl_policy", ssl_label)
                ssl.attr("name", _name(lb_label, str(listener.port), "tls"))
                ssl.attr("profile", policy_spec["profile"])
                ssl.attr("min_tls_version", policy_spec["min_tls"])
                proxy.attr("ssl_policy", Ref(f"google_compute_ssl_policy.{ssl_label}.id"))
        rule_kind = (
            "google_compute_forwarding_rule"
            if regional
            else "google_compute_global_forwarding_rule"
        )
        rule_label = state.labels.allocate(rule_kind, f"{lb_label}_{listener.port}")
        rule = file.block("resource", rule_kind, rule_label)
        rule.attr("name", _name(lb_label, str(listener.port)))
        if regional:
            rule.attr("region", Ref("var.region"))
            rule.attr("network", Ref(f"google_compute_network.{state.network_labels[network]}.id"))
            subnet_id = _require(lb, "subnet")
            rule.attr(
                "subnetwork", Ref(f"google_compute_subnetwork.{state.subnet_labels[subnet_id]}.id")
            )
        rule.attr("load_balancing_scheme", scheme)
        rule.attr("ip_protocol", "TCP")
        rule.attr("port_range", str(listener.port))
        rule.attr("target", Ref(f"{proxy_kind}.{proxy_label}.id"))
        if address_ref:
            rule.attr("ip_address", Ref(address_ref))
        if regional:
            rule.attr(
                "depends_on", [Ref(f"google_compute_subnetwork.{state.proxy_subnets[network]}")]
            )

    sources = (
        [_require(lb, "proxy_subnet_cidr")] + _PROXY_HEALTH_RANGES
        if regional
        else _PROXY_HEALTH_RANGES
    )
    _firewall(file, state, lb_label, network, sources, tgs, "backends")


def _passthrough(file: HclFile, state: _Context, lb: LoadBalancer, internal: bool) -> None:
    lb_label = state.labels.allocate("load_balancer", lb.id)
    network = _network_of(state, lb)
    skipped = set(lb.target_hints.get("skipped_listeners", []))
    scheme = "INTERNAL" if internal else "EXTERNAL"
    address_ref = None
    if not internal:
        address = file.block("resource", "google_compute_address", lb_label)
        address.comment("\n".join(_header_lines(lb, state.ctx.decided_by)))
        address.attr("name", _name(lb_label, "ip"))
        address.attr("region", Ref("var.region"))
        address_ref = f"google_compute_address.{lb_label}.address"
    services: dict[str, str] = {}
    used: list[TargetGroup] = []
    for listener in lb.listeners:
        if listener.port in skipped:
            continue
        targets = [t for t in listener.default_action.target_groups if t.target_group in state.tgs]
        if not targets:
            continue
        tg = state.tgs[targets[0].target_group]
        if tg.id not in services:
            services[tg.id] = _backend_service(
                file, state, lb, lb_label, tg, scheme=scheme, regional=True
            )
            used.append(tg)
        protocol = listener.protocol.upper()
        rule_label = state.labels.allocate(
            "google_compute_forwarding_rule", f"{lb_label}_{listener.port}"
        )
        rule = file.block("resource", "google_compute_forwarding_rule", rule_label)
        rule.attr("name", _name(lb_label, str(listener.port), protocol.lower()))
        rule.attr("region", Ref("var.region"))
        rule.attr("load_balancing_scheme", scheme)
        rule.attr("ip_protocol", "UDP" if protocol == "UDP" else "TCP")
        rule.attr("ports", [str(listener.port)])
        rule.attr("backend_service", Ref(services[tg.id]))
        if address_ref:
            rule.attr("ip_address", Ref(address_ref))
        else:
            subnet_id = _require(lb, "subnet")
            rule.attr("network", Ref(f"google_compute_network.{state.network_labels[network]}.id"))
            rule.attr(
                "subnetwork", Ref(f"google_compute_subnetwork.{state.subnet_labels[subnet_id]}.id")
            )
    sources = _PROXY_HEALTH_RANGES if internal else _PASSTHROUGH_EXTERNAL_HEALTH_RANGES
    # Client traffic keeps its source address, so the backends' migrated firewall rules govern it;
    # only health checks need a rule of their own.
    health_only = [tg.model_copy(update={"port": None}) for tg in used]
    _firewall(file, state, lb_label, network, sources, health_only, "health")
