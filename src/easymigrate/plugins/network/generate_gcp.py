"""Networking → GCP Terraform generation (spec §5.3, plan 4 A3/A4).

Reads only resolved IR and `target_hints`, and skips objects with `excluded` set.
Contains no difference logic: anything this module cannot represent (a PrefixListPeer,
ExternalPolicyPeer or a leftover ICMP type/code) means a difference rule failed to run,
and `GenerationError` guards that contract.
"""

from __future__ import annotations

from easymigrate.core.plugin import GenerateContext, GenerationError
from easymigrate.ir.base import IRDocument
from easymigrate.ir.network import (
    CidrPeer,
    ExternalPolicyPeer,
    FirewallPolicy,
    FirewallRule,
    Nat,
    Network,
    PolicyPeer,
    PrefixListPeer,
    SelfPeer,
    Subnet,
)
from easymigrate.providers.gcp.hcl import Block, HclFile, Ref
from easymigrate.providers.gcp.naming import GcpNameAllocator, TfLabelAllocator

_HEADER = "Generated by EasyMigrate {version}. Do not edit by hand; re-run easymigrate plan."

_DEFAULT_EGRESS_CIDR = "0.0.0.0/0"

# "peer kind" suffix used in <policy>-<in|eg>-<cidr|tag|self> firewall names (spec §5.3).
_PEER_SUFFIX = {CidrPeer: "cidr", PolicyPeer: "tag", SelfPeer: "self"}
_DIRECTION_SUFFIX = {"ingress": "in", "egress": "eg"}


def _slug(ir_id: str) -> str:
    return ir_id.split(":", 1)[1]


class _Names:
    """Allocates Terraform labels and GCP names from IR ids, and tracks the mapping so
    later resources can reference earlier ones (spec: names derive from the IR id, not
    the display name)."""

    def __init__(self) -> None:
        self.tf = TfLabelAllocator()
        self.gcp = GcpNameAllocator()
        self.label: dict[str, str] = {}
        self.name: dict[str, str] = {}

    def allocate(
        self,
        resource_type: str,
        ir_id: str,
        *,
        slug: str | None = None,
        rename_against: str | None = None,
    ) -> tuple[str, bool]:
        """Allocate a label and GCP name for `ir_id`. `rename_against`, when given, is
        the IR object's `name` field: GEN-RENAMED is only correct when the final GCP
        name differs from `name`, not from the id-derived slug used to build it."""
        label = self.tf.allocate(resource_type, ir_id)
        slug = slug if slug is not None else _slug(ir_id)
        gcp, _ = self.gcp.allocate(resource_type, slug)
        self.label[ir_id] = label
        self.name[ir_id] = gcp
        renamed = rename_against is not None and gcp != rename_against
        return label, renamed

    def allocate_extra(
        self, resource_type: str, synthetic_id: str, raw_name: str
    ) -> tuple[str, str]:
        """For resources with no single IR id of their own (e.g. one firewall group)."""
        label = self.tf.allocate(resource_type, synthetic_id)
        gcp, _ = self.gcp.allocate(resource_type, raw_name)
        return label, gcp


def _header_lines(
    obj, resolved_findings: list, decided_by: dict[str, str], extra: list[str] | None = None
) -> list[str]:
    lines = [f"from AWS {obj.source.type} {obj.source.id} ({obj.name})"]
    for ref in obj.resolution:
        by = decided_by.get(ref.key, "default")
        lines.append(f"decision {ref.key} → {ref.strategy} ({by})")
    for finding in resolved_findings:
        if finding.subject == obj.id and finding.level != "info":
            lines.append(f"⚠ {finding.code}: {finding.message}")
    if extra:
        lines.extend(extra)
    return lines


def _resource(
    file: HclFile, type_: str, label: str, obj, findings: list, decided_by: dict
) -> Block:
    block = file.block("resource", type_, label)
    block.comment("\n".join(_header_lines(obj, findings, decided_by)))
    return block


def _check_rule_allowed(rule: FirewallRule) -> None:
    if isinstance(rule.peer, (PrefixListPeer, ExternalPolicyPeer)):
        raise GenerationError(
            f"resolved IR still has a {type(rule.peer).__name__} peer; the matching "
            "difference rule should have removed it before generation"
        )
    if rule.icmp_type is not None:
        raise GenerationError(
            "resolved IR still has an ICMP type/code; NET-ICMP-TYPE should have cleared "
            "it before generation"
        )


def generate(resolved: IRDocument, ctx: GenerateContext) -> HclFile:
    file = HclFile(header=[_HEADER.format(version=ctx.version)])
    names = _Names()

    networks = [obj for obj in resolved.of_kind(Network) if obj.excluded is None]
    subnets = [obj for obj in resolved.of_kind(Subnet) if obj.excluded is None]
    nats = [obj for obj in resolved.of_kind(Nat) if obj.excluded is None]
    policies = [obj for obj in resolved.of_kind(FirewallPolicy) if obj.excluded is None]
    findings = resolved.findings
    decided_by = ctx.decided_by

    _generate_networks(file, names, networks, findings, decided_by, ctx)
    _generate_subnets(file, names, subnets, findings, decided_by, ctx)
    _generate_internet_routes(file, names, networks, subnets)
    _generate_nats(file, names, nats, subnets, findings, decided_by, ctx)
    network_cidrs = {net.id: list(net.cidr_blocks) for net in networks}
    _generate_firewalls(file, names, policies, network_cidrs, findings, decided_by, ctx)

    return file


def _generate_networks(file, names, networks, findings, decided_by, ctx) -> None:
    for net in sorted(networks, key=lambda n: n.id):
        label, renamed = names.allocate("google_compute_network", net.id, rename_against=net.name)
        if renamed:
            ctx.info(
                "GEN-RENAMED",
                f"{net.id} was renamed to {names.name[net.id]!r} to satisfy GCP naming rules",
                subject=net.id,
            )
        b = _resource(file, "google_compute_network", label, net, findings, decided_by)
        b.attr("name", names.name[net.id])
        b.attr("auto_create_subnetworks", False)
        b.attr("delete_default_routes_on_create", True)
        b.attr("routing_mode", "REGIONAL")


def _generate_subnets(file, names, subnets, findings, decided_by, ctx) -> None:
    for subnet in sorted(subnets, key=lambda s: s.id):
        label, renamed = names.allocate(
            "google_compute_subnetwork", subnet.id, rename_against=subnet.name
        )
        if renamed:
            ctx.info(
                "GEN-RENAMED",
                f"{subnet.id} was renamed to {names.name[subnet.id]!r} to satisfy GCP naming rules",
                subject=subnet.id,
            )
        extra = None
        if subnet.target_hints.get("no_external_ip"):
            extra = [
                "no_external_ip: enforced per-instance by later plugins; plan 4 networking "
                "has no VMs to configure yet"
            ]
        block = file.block("resource", "google_compute_subnetwork", label)
        block.comment("\n".join(_header_lines(subnet, findings, decided_by, extra)))
        block.attr("name", names.name[subnet.id])
        block.attr("ip_cidr_range", subnet.cidr)
        block.attr("region", Ref("var.region"))
        block.attr("network", Ref(f"google_compute_network.{names.label[subnet.network]}.id"))


def _generate_internet_routes(file, names, networks, subnets) -> None:
    subnets_by_network: dict[str, list[Subnet]] = {}
    for subnet in subnets:
        subnets_by_network.setdefault(subnet.network, []).append(subnet)

    for net in sorted(networks, key=lambda n: n.id):
        has_public = any(s.internet == "public" for s in subnets_by_network.get(net.id, []))
        if not has_public:
            continue
        synthetic_id = f"{net.id}-default-internet"
        label, gcp = names.allocate_extra(
            "google_compute_route", synthetic_id, f"{_slug(net.id)}-default-internet"
        )
        block = file.block("resource", "google_compute_route", label)
        block.comment(f"from AWS vpc {net.source.id} ({net.name}): default route to the internet")
        block.attr("name", gcp)
        block.attr("network", Ref(f"google_compute_network.{names.label[net.id]}.id"))
        block.attr("dest_range", "0.0.0.0/0")
        block.attr("next_hop_gateway", "default-internet-gateway")
        block.attr("priority", 1000)


def _generate_nats(file, names, nats, subnets, findings, decided_by, ctx) -> None:
    subnet_ids = {s.id for s in subnets}
    for nat in sorted(nats, key=lambda n: n.id):
        served = sorted(sid for sid in nat.serves_subnets if sid in subnet_ids)
        if not served:
            ctx.info("GEN-NAT-UNUSED", f"{nat.id} serves no subnets; skipped", subject=nat.id)
            continue

        # The router has a synthetic "<nat>-router" name, so it never matches nat.name;
        # the rename check belongs to the router_nat resource below, which carries the
        # nat's own GCP name.
        router_label, _ = names.allocate(
            "google_compute_router", nat.id, slug=f"{_slug(nat.id)}-router"
        )
        router = _resource(file, "google_compute_router", router_label, nat, findings, decided_by)
        router.attr("name", names.name[nat.id])
        router.attr("network", Ref(f"google_compute_network.{names.label[nat.network]}.id"))
        router.attr("region", Ref("var.region"))

        nat_label, nat_gcp = names.allocate_extra(
            "google_compute_router_nat", f"{nat.id}-nat", _slug(nat.id)
        )
        if nat_gcp != nat.name:
            ctx.info(
                "GEN-RENAMED",
                f"{nat.id} was renamed to {nat_gcp!r} to satisfy GCP naming rules",
                subject=nat.id,
            )
        block = file.block("resource", "google_compute_router_nat", nat_label)
        block.comment("\n".join(_header_lines(nat, findings, decided_by)))
        block.attr("name", nat_gcp)
        block.attr("router", Ref(f"google_compute_router.{router_label}.name"))
        block.attr("region", Ref("var.region"))
        block.attr("source_subnetwork_ip_ranges_to_nat", "LIST_OF_SUBNETWORKS")
        for sid in served:
            sub_block = block.block("subnetwork")
            sub_block.attr("name", Ref(f"google_compute_subnetwork.{names.label[sid]}.id"))
            sub_block.attr("source_ip_ranges_to_nat", ["ALL_IP_RANGES"])


def _peer_suffix(peer) -> str:
    return _PEER_SUFFIX[type(peer)]


def _generate_firewalls(file, names, policies, network_cidrs, findings, decided_by, ctx) -> None:
    policy_tag: dict[str, str] = {}
    policy_gcp_name: dict[str, str] = {}
    for policy in sorted(policies, key=lambda p: p.id):
        gcp, _ = names.gcp.allocate("network_tag", _slug(policy.id))
        policy_gcp_name[policy.id] = gcp
        policy_tag[policy.id] = f"fw-{gcp}"
        if gcp != policy.name:
            ctx.info(
                "GEN-RENAMED",
                f"{policy.id} was renamed to {gcp!r} to satisfy GCP naming rules",
                subject=policy.id,
            )

    for policy in sorted(policies, key=lambda p: p.id):
        _generate_policy_firewalls(
            file, names, policy, policy_tag, policy_gcp_name, network_cidrs, findings, decided_by
        )


def _generate_policy_firewalls(
    file, names, policy, policy_tag, policy_gcp_name, network_cidrs, findings, decided_by
) -> None:
    own_tag = policy_tag[policy.id]
    groups: dict[tuple[str, str], list[FirewallRule]] = {}
    skipped_default_egress = False

    for rule in policy.rules:
        _check_rule_allowed(rule)
        if (
            rule.direction == "egress"
            and isinstance(rule.peer, CidrPeer)
            and rule.protocol == "all"
            and rule.peer.cidr == _DEFAULT_EGRESS_CIDR
            and not skipped_default_egress
        ):
            skipped_default_egress = True
            continue
        key = (rule.direction, _peer_suffix(rule.peer))
        groups.setdefault(key, []).append(rule)

    for (direction, peer_suffix), rules in sorted(groups.items()):
        _generate_firewall_group(
            file,
            names,
            policy,
            direction,
            peer_suffix,
            rules,
            own_tag,
            policy_tag,
            policy_gcp_name,
            network_cidrs,
            findings,
            decided_by,
        )


def _ranges_for_group(
    direction: str, peer_suffix: str, rules, policy, own_tag, policy_tag, network_cidrs
) -> dict:
    """Build the source_ranges/source_tags/destination_ranges attribute for a group."""
    if peer_suffix == "cidr":
        ranges = sorted({rule.peer.cidr for rule in rules})
        return {"source_ranges" if direction == "ingress" else "destination_ranges": ranges}
    if peer_suffix == "tag":
        if direction == "ingress":
            tags = sorted({policy_tag[rule.peer.policy] for rule in rules})
            return {"source_tags": tags}
        ranges: set[str] = set()
        for rule in rules:
            egress_ranges = policy.target_hints.get("egress_ranges", {})
            ranges.update(egress_ranges.get(rule.peer.policy, []))
        return {"destination_ranges": sorted(ranges)}
    # self: GCP egress rules cannot target a tag, so a self-referencing egress rule (rare;
    # no AWS SG UI creates one, but the API allows it) falls back to this policy's own
    # network CIDR blocks, the closest concrete equivalent.
    if direction == "ingress":
        return {"source_tags": [own_tag]}
    return {"destination_ranges": sorted(network_cidrs.get(policy.network, []))}


def _generate_firewall_group(
    file,
    names,
    policy,
    direction,
    peer_suffix,
    rules,
    own_tag,
    policy_tag,
    policy_gcp_name,
    network_cidrs,
    findings,
    decided_by,
) -> None:
    dir_suffix = _DIRECTION_SUFFIX[direction]
    synthetic_id = f"{policy.id}-{dir_suffix}-{peer_suffix}"
    raw_name = f"{policy_gcp_name[policy.id]}-{dir_suffix}-{peer_suffix}"
    label, gcp = names.allocate_extra("google_compute_firewall", synthetic_id, raw_name)

    block = file.block("resource", "google_compute_firewall", label)
    block.comment("\n".join(_header_lines(policy, findings, decided_by)))
    block.attr("name", gcp)
    block.attr("network", Ref(f"google_compute_network.{names.label[policy.network]}.id"))
    block.attr("direction", direction.upper())
    block.attr("priority", 1000)
    block.attr("target_tags", [own_tag])

    ranges = _ranges_for_group(
        direction, peer_suffix, rules, policy, own_tag, policy_tag, network_cidrs
    )
    for key, value in ranges.items():
        block.attr(key, value)

    combos: list[tuple[str, tuple[str, ...]]] = []
    for rule in rules:
        combo = (rule.protocol, tuple(sorted(rule.ports)))
        if combo not in combos:
            combos.append(combo)
    combos.sort()

    # `allow` is a repeatable block in the google_compute_firewall schema, not a list
    # attribute (a real `tofu validate` run against the golden fixtures caught this).
    for protocol, ports in combos:
        allow_block = block.block("allow")
        allow_block.attr("protocol", protocol)
        if ports:
            allow_block.attr("ports", list(ports))


# --- "No silent mapping" field coverage (plan 4 A4) -----------------------------------
#
# Every field of every IR kind this generator consumes must be declared here. Allowed
# declaration values:
#   "exact"              copied as-is
#   "metadata"           kind/id/name/labels/source/resolution/excluded/target_hints
#                         bookkeeping (target_hints' individual keys are covered below
#                         by "hint:<key>" declarations on the kind that consumes them)
#   "rule:<RULE_ID>"      handled by a difference rule before generation
#   "hint:<key>"          a target_hints key this generator reads
#   "not_generated:<reason>"  intentionally not represented in GCP
#   "derived:<reason>"    consumed to drive generation, not copied verbatim
