def generate(resolved: IRDocument, ctx: GenerateContext) -> HclFile:
    file = HclFile(header=[_HEADER.format(version=ctx.version)])
    clusters = _live(resolved, KubernetesCluster)
    if not clusters and not _live(resolved, NodePool):
        return file

    subnet_labels = subnet_tf_labels(resolved)
    network_labels = network_tf_labels(resolved)
    live_ids = {cluster.id for cluster in clusters}
    pools = _live(resolved, NodePool)
    for pool in pools:
        if pool.cluster not in live_ids:
            raise GenerationError(
                f"{pool.id} belongs to {pool.cluster}, which is not generated; a node pool "
                "cannot exist without its cluster"
            )
    tags, _ = policy_network_tags(resolved.of_kind(FirewallPolicy))
    live_policies = {p.id for p in resolved.of_kind(FirewallPolicy) if p.excluded is None}

    names = _Names()
    for cluster in clusters:
        names.allocate("google_container_cluster", cluster.id)
    for pool in pools:
        names.allocate("google_container_node_pool", pool.id)
    for cluster in clusters:
        _generate_cluster(file, names, cluster, resolved, subnet_labels, network_labels, ctx)
        if cluster.target_hints.get("default_pool"):
            _generate_default_pool(file, names, cluster, ctx)
    for pool in pools:
        cluster = resolved.get(pool.cluster)
        pool_tags = sorted(tags[p] for p in pool.firewall_policies if p in live_policies)
        _generate_pool(file, names, pool, cluster, pool_tags, ctx)
    return file


def _zones(letters: list[str], ctx: GenerateContext, subject: str) -> list[Ref]:
    zones: dict[str, None] = {}
    for letter in letters:
        suffix, wrapped = zone_suffix(ctx.region, letter)
        if wrapped:
            ctx.info(
                "GEN-ZONE-WRAP",
                f"{subject}: its nodes spanned more zones than {ctx.region} has, so some share "
                f"zone {ctx.region}-{suffix}.",
                subject=subject,
            )
        zones[f'"${{var.region}}-{suffix}"'] = None
    return [Ref(expr) for expr in zones]


def _management(block, cluster: KubernetesCluster) -> None:
    management = block.block("management")
    management.attr("auto_repair", True)
    # Every release channel requires node auto-upgrade (K8S-VERSION).
    management.attr("auto_upgrade", bool(cluster.target_hints.get("node_auto_upgrade", True)))


def _generate_pool(
    file: HclFile,
    names: _Names,
    pool: NodePool,
    cluster: KubernetesCluster,
    pool_tags: list[str],
    ctx: GenerateContext,
) -> None:
    hints = pool.target_hints
    machine_type = _require(pool, "machine_type")
    image_type = _require(pool, "image_type")
    letters = hints.get("zone_letters")
    if not letters:
        raise GenerationError(f"{pool.id} has no zones: none of its subnets is in the scan")

    block = file.block("resource", "google_container_node_pool", names.label[pool.id])
    block.comment("\n".join(_header_lines(pool, ctx.decided_by)))
    block.attr("name", names.name[pool.id][:_POOL_NAME_MAX].rstrip("-"))
    block.attr("cluster", Ref(f"google_container_cluster.{names.label[cluster.id]}.id"))
    block.attr("location", Ref("var.region"))
    block.attr("node_locations", _zones(letters, ctx, pool.id))
    autoscaling = hints.get("autoscaling")
    if autoscaling:
        block.attr("initial_node_count", autoscaling["initial_per_zone"])
        scaling = block.block("autoscaling")
        scaling.attr("total_min_node_count", autoscaling["total_min"])
        scaling.attr("total_max_node_count", autoscaling["total_max"])
        scaling.attr("location_policy", "BALANCED")
    else:
        block.attr("node_count", _require(pool, "node_count_per_zone"))
    _management(block, cluster)
    if pool.max_unavailable is not None:
        upgrade = block.block("upgrade_settings")
        upgrade.attr("max_surge", 1)
        upgrade.attr("max_unavailable", pool.max_unavailable)

    node = block.block("node_config")
    node.attr("machine_type", machine_type)
    node.attr("image_type", image_type)
    if pool.disk_size_gib:
        node.attr("disk_size_gb", max(pool.disk_size_gib, _MIN_NODE_DISK_GB))
    node.attr("disk_type", "pd-balanced")
    if hints.get("spot"):
        node.attr("spot", True)
    if pool.node_labels:
        node.attr("labels", dict(sorted(pool.node_labels.items())))
    if pool.labels:
        node.attr("resource_labels", dict(sorted(pool.labels.items())))
    if pool_tags:
        node.attr("tags", pool_tags)
    node.attr("oauth_scopes", [_CLOUD_PLATFORM])
    for taint in pool.taints:
        entry = node.block("taint")
        entry.attr("key", taint.key)
        if taint.value is not None:
            entry.attr("value", taint.value)
        entry.attr("effect", taint.effect)
    node.block("workload_metadata_config").attr("mode", "GKE_METADATA")


def _generate_default_pool(
    file: HclFile, names: _Names, cluster: KubernetesCluster, ctx: GenerateContext
) -> None:
    """The pool K8S-FARGATE adds to a cluster that ran only on Fargate."""
    spec = cluster.target_hints["default_pool"]
    label = f"{names.label[cluster.id]}_fargate"
    block = file.block("resource", "google_container_node_pool", label)
    block.comment(f"replaces the Fargate profiles of {cluster.id} (K8S-FARGATE)")
    block.attr("name", f"{names.name[cluster.id][: _POOL_NAME_MAX - 8]}-fargate")
    block.attr("cluster", Ref(f"google_container_cluster.{names.label[cluster.id]}.id"))
    block.attr("location", Ref("var.region"))
    block.attr("node_count", spec["nodes_per_zone"])
    _management(block, cluster)
    node = block.block("node_config")
    node.attr("machine_type", spec["machine_type"])
    node.attr("image_type", "COS_CONTAINERD")
    node.attr("oauth_scopes", [_CLOUD_PLATFORM])
    node.block("workload_metadata_config").attr("mode", "GKE_METADATA")


class _Names:
    def __init__(self) -> None:
        self.tf = TfLabelAllocator()
        self.gcp = GcpNameAllocator()
        self.label: dict[str, str] = {}
        self.name: dict[str, str] = {}

    def allocate(self, resource_type: str, ir_id: str) -> None:
        self.label[ir_id] = self.tf.allocate(resource_type, ir_id)
        self.name[ir_id], _ = self.gcp.allocate(resource_type, ir_id.split(":", 1)[1])


def _live(resolved: IRDocument, kind) -> list:
    return sorted((o for o in resolved.of_kind(kind) if o.excluded is None), key=lambda o: o.id)


def _header_lines(obj, decided_by: dict[str, str]) -> list[str]:
    lines = [f"from AWS {obj.source.type} {obj.source.id} ({obj.name})"]
    for ref in obj.resolution:
        lines.append(f"decision {ref.key} → {ref.strategy} ({decided_by.get(ref.key, 'default')})")
    return lines


def _require(obj, key: str):
    value = obj.target_hints.get(key)
    if value is None:
        raise GenerationError(
            f"{obj.id} has no {key!r} target hint; a K8S-* difference rule did not run"
        )
    return value


def _generate_cluster(
    file: HclFile,
    names: _Names,
    cluster: KubernetesCluster,
    resolved: IRDocument,
    subnet_labels: dict[str, str],
    network_labels: dict[str, str],
    ctx: GenerateContext,
) -> None:
    hints = cluster.target_hints
    subnet_id = _require(cluster, "subnet")
    channel = _require(cluster, "release_channel")
    if subnet_id not in subnet_labels:
        raise GenerationError(f"{cluster.id} uses {subnet_id}, which is not generated")
    subnet = resolved.get(subnet_id)

    block = file.block("resource", "google_container_cluster", names.label[cluster.id])
    block.comment("\n".join(_header_lines(cluster, ctx.decided_by)))
    block.attr("name", names.name[cluster.id])
    # Regional: an EKS control plane spans AZs, and a zonal GKE one would not (spec 5 D5).
    block.attr("location", Ref("var.region"))
    block.attr("network", Ref(f"google_compute_network.{network_labels[subnet.network]}.id"))
    block.attr("subnetwork", Ref(f"google_compute_subnetwork.{subnet_labels[subnet_id]}.id"))
    # Node pools are separate resources; the default pool GKE insists on is removed at once.
    block.attr("remove_default_node_pool", True)
    block.attr("initial_node_count", 1)
    # The provider defaults this to true. EKS has no such setting, and true blocks teardown.
    block.attr("deletion_protection", False)
    if hints.get("version"):
        block.attr("min_master_version", hints["version"])
    block.attr("networking_mode", "VPC_NATIVE")
    if cluster.labels:
        block.attr("resource_labels", dict(sorted(cluster.labels.items())))

    # GKE still builds the default pool before removing it: one node per zone with a 100 GB
    # SSD-class disk, which alone exceeded a common 250 GB regional SSD quota (live run,
    # 2026-09-22). Small standard disks keep that throwaway pool out of the SSD quota.
    bootstrap = block.block("node_config")
    bootstrap.attr("disk_size_gb", 20)
    bootstrap.attr("disk_type", "pd-standard")
    block.block("release_channel").attr("channel", channel)
    ranges = block.block("ip_allocation_policy")
    ranges.attr("cluster_secondary_range_name", _require(cluster, "pods_range"))
    ranges.attr("services_secondary_range_name", _require(cluster, "services_range"))

    endpoint = hints.get("endpoint") or {"private_endpoint": False, "authorized_networks": None}
    private_nodes = hints.get("private_nodes", True)
    if private_nodes or endpoint["private_endpoint"]:
        private = block.block("private_cluster_config")
        private.attr("enable_private_nodes", private_nodes)
        private.attr("enable_private_endpoint", endpoint["private_endpoint"])
    if endpoint["authorized_networks"] is not None:
        authorized = block.block("master_authorized_networks_config")
        for cidr in endpoint["authorized_networks"]:
            entry = authorized.block("cidr_blocks")
            entry.attr("cidr_block", cidr)
            entry.attr("display_name", f"from EKS publicAccessCidrs {cidr}")

    # Always on, so each IRSA / Pod Identity binding can be recreated (K8S-IAM-FOR-PODS).
    block.block("workload_identity_config").attr(
        "workload_pool", Ref('"${var.project}.svc.id.goog"')
    )
    components = hints.get("logging_components")
    if components:
        block.block("logging_config").attr("enable_components", components)
    if "filestore_csi" in hints.get("gke_addons", []):
        addons = block.block("addons_config")
        addons.block("gcp_filestore_csi_driver_config").attr("enabled", True)
    # After the default pool is removed the provider reads node_config back from a surviving
    # pool, so without this every later plan wants to "update" it (live run, 2026-09-22).
    block.block("lifecycle").attr("ignore_changes", [Ref("node_config")])
