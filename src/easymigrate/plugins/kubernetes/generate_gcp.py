"""Kubernetes → GKE Terraform generation (spec 5 §6).

Reads only resolved IR and `target_hints`. Anything it cannot represent means a K8S-* rule did not
run, and `GenerationError` guards that contract (spec 5 §6).
"""

from __future__ import annotations

from easymigrate.core.plugin import GenerateContext, GenerationError
from easymigrate.ir.base import IRDocument
from easymigrate.ir.kubernetes import KubernetesCluster
from easymigrate.plugins.network.generate_gcp import network_tf_labels, subnet_tf_labels
from easymigrate.providers.gcp.hcl import HclFile, Ref
from easymigrate.providers.gcp.naming import GcpNameAllocator, TfLabelAllocator

