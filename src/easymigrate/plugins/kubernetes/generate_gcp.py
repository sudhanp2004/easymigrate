def generate(resolved: IRDocument, ctx: GenerateContext) -> HclFile:
    file = HclFile(header=[_HEADER.format(version=ctx.version)])
    clusters = _live(resolved, KubernetesCluster)
    if not clusters:
        return file

    subnet_labels = subnet_tf_labels(resolved)
    network_labels = network_tf_labels(resolved)
    names = _Names()
    for cluster in clusters:
        names.allocate("google_container_cluster", cluster.id)
    for cluster in clusters:
        _generate_cluster(file, names, cluster, resolved, subnet_labels, network_labels, ctx)
    return file


class _Names:
    def __init__(self) -> None:
        self.tf = TfLabelAllocator()
        self.gcp = GcpNameAllocator()
        self.label: dict[str, str] = {}
        self.name: dict[str, str] = {}

    def allocate(self, resource_type: str, ir_id: str) -> None:
        self.label[ir_id] = self.tf.allocate(resource_type, ir_id)
        self.name[ir_id], _ = self.gcp.allocate(resource_type, ir_id.split(":", 1)[1])


def _live(resolved: IRDocument, kind) -> list:
    return sorted((o for o in resolved.of_kind(kind) if o.excluded is None), key=lambda o: o.id)


def _header_lines(obj, decided_by: dict[str, str]) -> list[str]:
    lines = [f"from AWS {obj.source.type} {obj.source.id} ({obj.name})"]
    for ref in obj.resolution:
        lines.append(f"decision {ref.key} → {ref.strategy} ({decided_by.get(ref.key, 'default')})")
    return lines


def _require(obj, key: str):
    value = obj.target_hints.get(key)
    if value is None:
        raise GenerationError(
            f"{obj.id} has no {key!r} target hint; a K8S-* difference rule did not run"
        )
    return value


def _generate_cluster(
    file: HclFile,
    names: _Names,
    cluster: KubernetesCluster,
    resolved: IRDocument,
    subnet_labels: dict[str, str],
    network_labels: dict[str, str],
    ctx: GenerateContext,
) -> None:
    hints = cluster.target_hints
    subnet_id = _require(cluster, "subnet")
    channel = _require(cluster, "release_channel")
    if subnet_id not in subnet_labels:
        raise GenerationError(f"{cluster.id} uses {subnet_id}, which is not generated")
    subnet = resolved.get(subnet_id)

    block = file.block("resource", "google_container_cluster", names.label[cluster.id])
    block.comment("\n".join(_header_lines(cluster, ctx.decided_by)))
    block.attr("name", names.name[cluster.id])
    # Regional: an EKS control plane spans AZs, and a zonal GKE one would not (spec 5 D5).
    block.attr("location", Ref("var.region"))
    block.attr("network", Ref(f"google_compute_network.{network_labels[subnet.network]}.id"))
    block.attr("subnetwork", Ref(f"google_compute_subnetwork.{subnet_labels[subnet_id]}.id"))
    # Node pools are separate resources; the default pool GKE insists on is removed at once.
    block.attr("remove_default_node_pool", True)
    block.attr("initial_node_count", 1)
    # The provider defaults this to true. EKS has no such setting, and true blocks teardown.
    block.attr("deletion_protection", False)
    if channel == "UNSPECIFIED":
        block.attr("min_master_version", _require(cluster, "version"))
    block.attr("networking_mode", "VPC_NATIVE")
    if cluster.labels:
        block.attr("resource_labels", dict(sorted(cluster.labels.items())))

    block.block("release_channel").attr("channel", channel)
    ranges = block.block("ip_allocation_policy")
    ranges.attr("cluster_secondary_range_name", _require(cluster, "pods_range"))
    ranges.attr("services_secondary_range_name", _require(cluster, "services_range"))

    endpoint = hints.get("endpoint") or {"private_endpoint": False, "authorized_networks": None}
    private_nodes = hints.get("private_nodes", True)
    if private_nodes or endpoint["private_endpoint"]:
        private = block.block("private_cluster_config")
        private.attr("enable_private_nodes", private_nodes)
        private.attr("enable_private_endpoint", endpoint["private_endpoint"])
    if endpoint["authorized_networks"] is not None:
        authorized = block.block("master_authorized_networks_config")
        for cidr in endpoint["authorized_networks"]:
            entry = authorized.block("cidr_blocks")
            entry.attr("cidr_block", cidr)
            entry.attr("display_name", f"from EKS publicAccessCidrs {cidr}")

    # Always on, so each IRSA / Pod Identity binding can be recreated (K8S-IAM-FOR-PODS).
    block.block("workload_identity_config").attr(
        "workload_pool", Ref('"${var.project}.svc.id.goog"')
    )
    components = hints.get("logging_components")
    if components:
        block.block("logging_config").attr("enable_components", components)
    if "filestore_csi" in hints.get("gke_addons", []):
        addons = block.block("addons_config")
        addons.block("gcp_filestore_csi_driver_config").attr("enabled", True)
