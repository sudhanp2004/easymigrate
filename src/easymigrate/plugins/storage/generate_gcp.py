"""S3 → Cloud Storage Terraform generation (spec 6 §6).

Reads only resolved IR and `target_hints`. Anything it cannot represent means an S3-* rule did not
run, and `GenerationError` guards that contract.
"""

from __future__ import annotations

from easymigrate.core.plugin import GenerateContext, GenerationError
from easymigrate.ir.base import IRDocument
from easymigrate.ir.storage import StorageBucket
from easymigrate.providers.gcp.hcl import HclFile, Ref
from easymigrate.providers.gcp.naming import TfLabelAllocator

_HEADER = "Generated by EasyMigrate {version}. Do not edit by hand; re-run easymigrate plan."

_METADATA_FIELDS = {
    field: "metadata"
    for field in (
        "kind",
        "id",
        "name",
        "labels",
        "source",
        "target_hints",
        "resolution",
        "excluded",
    )
}
_RECORDED = "recorded:captured in the IR and the report; nothing is generated from it"

FIELD_COVERAGE: dict[str, dict[str, str]] = {
    "storage_bucket": {
        **_METADATA_FIELDS,
        "bucket_name": "decision:S3-BUCKET-NAME",
        "region": "derived:the bucket is created in the destination region",
        "versioning": "exact:versioning.enabled (suspended becomes disabled; S3-OBJECT-LOCK)",
        "encryption": "derived:Cloud Storage always encrypts at rest",
        "kms_key": "decision:S3-ENCRYPTION-KMS; an AWS KMS key cannot be used by GCP",
        "public_access_blocked": "exact:public_access_prevention = enforced",
        "public_via_policy": "decision:S3-PUBLIC-ACCESS",
        "public_via_acl": "decision:S3-PUBLIC-ACCESS",
        "has_policy": "always_excluded:S3-BUCKET-POLICY; statements are not translated",
        "object_ownership": "decision:S3-ACLS sets uniform_bucket_level_access",
        "lifecycle_rules": "decision:S3-LIFECYCLE",
        "cors_rules": "exact:cors blocks; allowed headers dropped (S3-CORS)",
        "website": "decision:S3-WEBSITE",
        "logging_bucket": "decision:S3-ACCESS-LOGGING",
        "logging_prefix": "decision:S3-ACCESS-LOGGING",
        "object_lock_enabled": _RECORDED,
        "object_lock": "decision:S3-OBJECT-LOCK sets retention_policy",
        "replication_destinations": "always_excluded:S3-REPLICATION",
        "notifications": "always_excluded:S3-NOTIFICATIONS",
        "requester_pays": "exact:requester_pays",
        "acceleration": "always_excluded:S3-ACCELERATION",
        "intelligent_tiering": "decision:S3-INTELLIGENT-TIERING enables autoclass",
    },
}

_DAY_SECONDS = 86400


def _header_lines(obj, decided_by: dict[str, str]) -> list[str]:
    lines = [f"from AWS {obj.source.type} {obj.source.id}"]
    for ref in obj.resolution:
        lines.append(f"decision {ref.key} → {ref.strategy} ({decided_by.get(ref.key, 'default')})")
    return lines


def _require(obj, key: str):
    value = obj.target_hints.get(key)
    if value is None:
        raise GenerationError(
            f"{obj.id} has no {key!r} target hint; an S3-* difference rule did not run"
        )
    return value


def generate(resolved: IRDocument, ctx: GenerateContext) -> HclFile:
    file = HclFile(header=[_HEADER.format(version=ctx.version)])
    buckets = sorted(
        (b for b in resolved.of_kind(StorageBucket) if b.excluded is None), key=lambda b: b.id
    )
    if not buckets:
        return file

    labels = TfLabelAllocator()
    tf_label = {b.id: labels.allocate("google_storage_bucket", b.id) for b in buckets}
    gcs_name = {b.id: _require(b, "gcs_name") for b in buckets}
    seen: dict[str, str] = {}
    for bucket_id, name in gcs_name.items():
        if name in seen:
            raise GenerationError(f"{seen[name]} and {bucket_id} would both be named {name!r}")
        seen[name] = bucket_id

    for bucket in buckets:
        _generate_bucket(file, bucket, tf_label, gcs_name, ctx)
    return file


def _generate_bucket(
    file: HclFile,
    bucket: StorageBucket,
    tf_label: dict[str, str],
    gcs_name: dict[str, str],
    ctx: GenerateContext,
) -> None:
    hints = bucket.target_hints
    label = tf_label[bucket.id]
    public = bool(hints.get("public"))
    block = file.block("resource", "google_storage_bucket", label)
    lines = _header_lines(bucket, ctx.decided_by)
    if gcs_name[bucket.id] != bucket.bucket_name:
        lines.append(f"renamed from S3 bucket {bucket.bucket_name}")
    block.comment("\n".join(lines))
    block.attr("name", gcs_name[bucket.id])
    block.attr("location", Ref("upper(var.region)"))
    block.attr("storage_class", "STANDARD")
    # force_destroy is deliberately left unset: a bucket that gained objects must not vanish on
    # teardown (spec 6 D6).
    block.attr("uniform_bucket_level_access", hints.get("uniform_access", True))
    # A public bucket needs prevention left to the org policy; everything else is enforced private.
    block.attr("public_access_prevention", "inherited" if public else "enforced")
    if bucket.requester_pays:
        block.attr("requester_pays", True)
    if bucket.labels:
        block.attr("labels", dict(sorted(bucket.labels.items())))

    # S3-OBJECT-LOCK turns versioning off when it adds a retention policy: GCS allows only one.
    versioned = bucket.versioning == "enabled" and not hints.get("versioning_off")
    if hints.get("retention") and versioned:
        raise GenerationError(f"{bucket.id} has both a retention policy and versioning")
    if hints.get("object_retention"):
        block.attr("enable_object_retention", True)
    block.block("versioning").attr("enabled", versioned)
    if hints.get("autoclass") and any(
        r["action"]["type"] == "SetStorageClass" for r in hints.get("lifecycle", [])
    ):
        raise GenerationError(f"{bucket.id} has Autoclass and storage-class lifecycle rules")
    if hints.get("autoclass"):
        block.block("autoclass").attr("enabled", True)
    for rule in hints.get("lifecycle", []):
        lifecycle = block.block("lifecycle_rule")
        action = lifecycle.block("action")
        action.attr("type", rule["action"]["type"])
        if "storage_class" in rule["action"]:
            action.attr("storage_class", rule["action"]["storage_class"])
        condition = lifecycle.block("condition")
        for key in (
            "age",
            "days_since_noncurrent_time",
            "num_newer_versions",
            "with_state",
            "matches_prefix",
            "matches_storage_class",
        ):
            if key in rule["condition"]:
                condition.attr(key, rule["condition"][key])
    for cors in bucket.cors_rules:
        entry = block.block("cors")
        entry.attr("origin", cors.origins)
        entry.attr("method", cors.methods)
        if cors.expose_headers:
            entry.attr("response_header", cors.expose_headers)
        if cors.max_age is not None:
            entry.attr("max_age_seconds", cors.max_age)
    website = hints.get("website")
    if website:
        site = block.block("website")
        if website.get("main_page_suffix"):
            site.attr("main_page_suffix", website["main_page_suffix"])
        if website.get("not_found_page"):
            site.attr("not_found_page", website["not_found_page"])
    logging = hints.get("logging")
    if logging:
        target = logging["target"]
        if target not in tf_label:
            raise GenerationError(f"{bucket.id} logs to {target}, which is not generated")
        log = block.block("logging")
        log.attr("log_bucket", Ref(f"google_storage_bucket.{tf_label[target]}.name"))
        if logging.get("prefix"):
            log.attr("log_object_prefix", logging["prefix"])
    retention = hints.get("retention")
    if retention:
        policy = block.block("retention_policy")
        policy.attr("retention_period", retention["days"] * _DAY_SECONDS)
        policy.attr("is_locked", retention["locked"])

    if public:
        member = file.block("resource", "google_storage_bucket_iam_member", f"{label}_public")
        member.comment(f"public read for {bucket.id} (S3-PUBLIC-ACCESS)")
        member.attr("bucket", Ref(f"google_storage_bucket.{label}.name"))
        member.attr("role", "roles/storage.objectViewer")
        member.attr("member", "allUsers")
