"""Database → GCP Terraform generation (spec §6, plan 3 A1/A2).

Reads only resolved IR and `target_hints`, and skips objects with `excluded` set.
Contains no difference logic: anything this module cannot represent (a missing
`database_version`/`tier` hint, an unresolved private network, a replica of an
`external:` primary, or leftover `parameters` with no flags/dropped-parameters hint)
means a difference rule failed to run, and `GenerationError` guards that contract.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field

from easymigrate.core.plugin import GenerateContext, GenerationError
from easymigrate.ir.base import IRDocument
from easymigrate.ir.database import DatabaseInstance
from easymigrate.ir.network import Network
from easymigrate.providers.gcp.hcl import HclFile, Ref
from easymigrate.providers.gcp.naming import (
    MAX_CLOUDSQL_NAME,
    GcpNameAllocator,
    TfLabelAllocator,
    gcp_name,
)

_HEADER = "Generated by EasyMigrate {version}. Do not edit by hand; re-run easymigrate plan."

# Cloud SQL's own default master username per engine, used when the source instance
# never captured one.
_DEFAULT_USERNAME = {"postgres": "postgres", "mysql": "root"}


def _slug(ir_id: str) -> str:
    return ir_id.split(":", 1)[1]


def _cidr_slug(cidr: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", cidr.lower()).strip("-") or "cidr"


def _header_lines(obj, decided_by: dict[str, str], extra: list[str] | None = None) -> list[str]:
    lines = [f"from AWS {obj.source.type} {obj.source.id} ({obj.name})"]
    for ref in obj.resolution:
        by = decided_by.get(ref.key, "default")
        lines.append(f"decision {ref.key} → {ref.strategy} ({by})")
    if extra:
        lines.extend(extra)
    return lines


@dataclass
class _Names:
    """Allocates Terraform labels (and, for instances, GCP names) from IR ids."""

    tf: TfLabelAllocator = field(default_factory=TfLabelAllocator)
    gcp: GcpNameAllocator = field(default_factory=GcpNameAllocator)
    label: dict[str, str] = field(default_factory=dict)
    name: dict[str, str] = field(default_factory=dict)

    def allocate(
        self, resource_type: str, ir_id: str, *, rename_against: str | None = None
    ) -> tuple[str, str, bool]:
        """Allocate a label and GCP name for `ir_id`. `rename_against`, when given, is
        the IR object's `name` field: GEN-RENAMED is only correct when the final GCP
        name differs from `name`, not from the id-derived slug used to build it."""
        label = self.tf.allocate(resource_type, ir_id)
        gcp, _ = self.gcp.allocate(resource_type, _slug(ir_id))
        self.label[ir_id] = label
        self.name[ir_id] = gcp
        renamed = rename_against is not None and gcp != rename_against
        return label, gcp, renamed


def _network_names(resolved: IRDocument) -> _Names:
    """Reproduce plugins/network/generate_gcp.py's `google_compute_network` label/name
    allocation exactly (same filter, same sort, same allocator), so this generator can
    build a matching `google_compute_network.<label>` reference without importing that
    module's private state."""
    names = _Names()
    networks = sorted(
        (obj for obj in resolved.of_kind(Network) if obj.excluded is None), key=lambda n: n.id
    )
    for net in networks:
        names.allocate("google_compute_network", net.id)
    return names


def _instance_order(instance: DatabaseInstance) -> tuple[int, str]:
    return (0 if instance.role == "primary" else 1, instance.id)


def _non_excluded_instances(resolved: IRDocument) -> list[DatabaseInstance]:
    return sorted(
        (i for i in resolved.of_kind(DatabaseInstance) if i.excluded is None),
        key=_instance_order,
    )


def database_password_variables(resolved: IRDocument) -> dict[str, str]:
    """IR id -> Terraform variable name, for every non-excluded primary instance. Used
    both by `generate()` (to name its `variable` blocks) and by plan 4's `plan` (to
    write secrets.auto.tfvars.json), so the two can never drift: both derive the name
    from the same pure function of the instance id alone."""
    variables: dict[str, str] = {}
    for instance in _non_excluded_instances(resolved):
        if instance.role != "primary":
            continue
        label = re.sub(r"[^a-z0-9_]+", "_", _slug(instance.id).lower()).strip("_")
        variables[instance.id] = f"db_password_{label}"
    return variables


def _require_hint(instance: DatabaseInstance, key: str, rule: str):
    if key not in instance.target_hints:
        raise GenerationError(
            f"{instance.id} has no target_hints[{key!r}]; {rule} should have set it "
            "before generation"
        )
    return instance.target_hints[key]


def generate(resolved: IRDocument, ctx: GenerateContext) -> HclFile:
    file = HclFile(header=[_HEADER.format(version=ctx.version)])
    net_names = _network_names(resolved)
    instances = _non_excluded_instances(resolved)
    decided_by = ctx.decided_by

    _check_replica_and_param_contracts(instances)
    psa_ranges = _psa_ranges_by_network(instances)
    _generate_psa(file, net_names, psa_ranges)

    names = _Names(gcp=GcpNameAllocator(max_length=MAX_CLOUDSQL_NAME))
    for instance in instances:
        _, gcp_instance_name, renamed = names.allocate(
            "google_sql_database_instance", instance.id, rename_against=instance.name
        )
        if renamed:
            ctx.info(
                "GEN-RENAMED",
                f"{instance.id} was renamed to {gcp_instance_name!r} to satisfy GCP naming rules",
                subject=instance.id,
            )

    password_vars = database_password_variables(resolved)

    for instance in instances:
        _generate_instance(file, names, net_names, instance, decided_by, ctx.region)
    for instance in instances:
        if instance.role == "primary" and instance.initial_database:
            _generate_database(file, names, instance)
    for instance in instances:
        if instance.role == "primary":
            _generate_user(file, names, instance, password_vars)
    for instance in instances:
        if instance.role == "primary":
            _generate_password_variable(file, password_vars[instance.id])

    return file


# ---- Private Services Access ------------------------------------------------------


def _psa_ranges_by_network(instances: list[DatabaseInstance]) -> dict[str, dict]:
    """network id -> {"range", "prefix_length"}, one entry per network that needs PSA.
    Raises when two instances in the same network resolved to different ranges: that
    is a plan-2 allocation bug (DB-PRIVATE-IP and DB-PUBLIC-ACCESS allocate
    independently), never something to silently pick one of."""
    seen: dict[str, tuple[dict, str]] = {}
    conflicts: dict[str, list[str]] = {}
    for instance in instances:
        psa = instance.target_hints.get("psa")
        if psa is None:
            continue
        network_id = instance.target_hints.get("private_network")
        if network_id is None:
            raise GenerationError(
                f"{instance.id} has target_hints['psa'] but no target_hints['private_network']; "
                "DB-PRIVATE-IP/DB-PUBLIC-ACCESS should have set both together"
            )
        if network_id in seen and seen[network_id][0] != psa:
            conflicts.setdefault(network_id, [seen[network_id][1]]).append(instance.id)
        elif network_id not in seen:
            seen[network_id] = (psa, instance.id)
    if conflicts:
        parts = [
            f"{network_id} via {', '.join(sorted(ids))}" for network_id, ids in conflicts.items()
        ]
        raise GenerationError(
            "conflicting Private Services Access ranges allocated for one network "
            f"({'; '.join(parts)}); DB-PRIVATE-IP and DB-PUBLIC-ACCESS allocate PSA ranges "
            "independently and must never hand one network two different ranges"
        )
    return {network_id: psa for network_id, (psa, _instance_id) in seen.items()}


def _generate_psa(file: HclFile, net_names: _Names, psa_ranges: dict[str, dict]) -> None:
    for network_id in sorted(psa_ranges):
        if network_id not in net_names.label:
            raise GenerationError(
                f"target_hints['private_network'] {network_id!r} does not name a network in "
                "this document"
            )
        psa = psa_ranges[network_id]
        network_label = net_names.label[network_id]
        network_gcp_name = net_names.name[network_id]
        label = f"{network_label}_psa"
        psa_name = gcp_name(f"{network_gcp_name}-psa")

        address = file.block("resource", "google_compute_global_address", label)
        address.attr("name", psa_name)
        address.attr("purpose", "VPC_PEERING")
        address.attr("address_type", "INTERNAL")
        address.attr("prefix_length", psa["prefix_length"])
        address.attr("address", psa["range"])
        address.attr("network", Ref(f"google_compute_network.{network_label}.id"))

        connection = file.block("resource", "google_service_networking_connection", label)
        connection.attr("network", Ref(f"google_compute_network.{network_label}.id"))
        connection.attr("service", "servicenetworking.googleapis.com")
        connection.attr(
            "reserved_peering_ranges",
            [Ref(f"google_compute_global_address.{label}.name")],
        )


# ---- google_sql_database_instance --------------------------------------------------


def _check_replica_and_param_contracts(instances: list[DatabaseInstance]) -> None:
    for instance in instances:
        if instance.role == "read_replica" and instance.replica_of.startswith("external:"):
            raise GenerationError(
                f"{instance.id} is a non-excluded replica of {instance.replica_of!r}; "
                "DB-REPLICA should have excluded a replica of an external primary before "
                "generation"
            )
        if instance.parameters and (
            "database_flags" not in instance.target_hints
            and "dropped_parameters" not in instance.target_hints
        ):
            raise GenerationError(
                f"{instance.id} has non-empty parameters but no target_hints['database_flags'] "
                "or target_hints['dropped_parameters']; DB-PARAM-FLAGS should have run"
            )


def _generate_instance(
    file: HclFile,
    names: _Names,
    net_names: _Names,
    instance: DatabaseInstance,
    decided_by: dict[str, str],
    region: str,
) -> None:
    label = names.label[instance.id]
    version = _require_hint(instance, "database_version", "DB-ENGINE-VERSION")
    _require_hint(instance, "tier", "DB-TIER")

    public_ip = instance.target_hints.get("public_ip", False)
    private_network = instance.target_hints.get("private_network")
    if not public_ip and private_network is None:
        raise GenerationError(
            f"{instance.id} has neither target_hints['public_ip'] nor "
            "target_hints['private_network'] set; DB-PRIVATE-IP/DB-PUBLIC-ACCESS should "
            "have set one"
        )
    if private_network is not None and private_network not in net_names.label:
        raise GenerationError(
            f"{instance.id}'s target_hints['private_network'] {private_network!r} does not "
            "name a network in this document"
        )

    if instance.role == "read_replica":
        primary_id = _require_hint(instance, "master_instance", "DB-REPLICA")
        if primary_id not in names.label:
            raise GenerationError(
                f"{instance.id}'s target_hints['master_instance'] {primary_id!r} is not a "
                "non-excluded instance in this document"
            )

    extra = [f"instance class: {instance.compute.class_name}"]
    block = file.block("resource", "google_sql_database_instance", label)
    block.comment("\n".join(_header_lines(instance, decided_by, extra)))
    block.attr("name", names.name[instance.id])
    block.attr("database_version", version)
    block.attr("region", region)
    block.attr("deletion_protection", instance.deletion_protection)

    settings = block.block("settings")
    _generate_settings(settings, instance, net_names, public_ip, private_network)

    if instance.role == "read_replica":
        primary_label = names.label[instance.target_hints["master_instance"]]
        block.attr(
            "master_instance_name", Ref(f"google_sql_database_instance.{primary_label}.name")
        )

    if private_network is not None:
        psa_label = f"{net_names.label[private_network]}_psa"
        block.attr("depends_on", [Ref(f"google_service_networking_connection.{psa_label}")])

    if instance.role == "read_replica":
        replica_config = block.block("replica_configuration")
        replica_config.attr("failover_target", False)


def _generate_settings(settings, instance, net_names, public_ip, private_network) -> None:
    hints = instance.target_hints
    settings.attr("tier", hints["tier"])
    settings.attr("availability_type", hints.get("availability_type", "ZONAL"))
    settings.attr("disk_size", hints.get("disk_size", instance.storage.size_gib))
    settings.attr("disk_type", hints.get("disk_type", "PD_SSD"))
    autoresize = hints.get("disk_autoresize", False)
    settings.attr("disk_autoresize", autoresize)
    if autoresize:
        settings.attr("disk_autoresize_limit", hints["disk_autoresize_limit"])
    settings.attr("deletion_protection_enabled", instance.deletion_protection)
    if instance.labels:
        settings.attr("user_labels", dict(instance.labels))

    if instance.role == "primary":
        _generate_backup_configuration(settings, instance)

    maintenance_window = hints.get("maintenance_window")
    if maintenance_window is not None:
        mw = settings.block("maintenance_window")
        mw.attr("day", maintenance_window["day"])
        mw.attr("hour", maintenance_window["hour"])

    flags = hints.get("database_flags", {})
    for name in sorted(flags):
        flag = settings.block("database_flags")
        flag.attr("name", name)
        flag.attr("value", flags[name])

    ip_config = settings.block("ip_configuration")
    ip_config.attr("ipv4_enabled", public_ip)
    if private_network is not None:
        ip_config.attr(
            "private_network", Ref(f"google_compute_network.{net_names.label[private_network]}.id")
        )
    if public_ip:
        ip_config.attr("ssl_mode", "ENCRYPTED_ONLY")
    for cidr in hints.get("authorized_networks", []):
        an = ip_config.block("authorized_networks")
        an.attr("name", _cidr_slug(cidr))
        an.attr("value", cidr)


def _generate_backup_configuration(settings, instance) -> None:
    backup = instance.target_hints.get("backup", {"enabled": False})
    pitr = instance.target_hints.get("pitr", {"enabled": False})

    block = settings.block("backup_configuration")
    block.attr("enabled", backup.get("enabled", False))
    if backup.get("enabled"):
        block.attr("start_time", backup["start_time"])

    pitr_attr = (
        "point_in_time_recovery_enabled"
        if instance.engine == "postgres"
        else ("binary_log_enabled")
    )
    block.attr(pitr_attr, pitr.get("enabled", False))
    if pitr.get("enabled"):
        block.attr("transaction_log_retention_days", pitr["log_retention_days"])

    if backup.get("enabled"):
        retention = block.block("backup_retention_settings")
        retention.attr("retained_backups", backup["retained_backups"])


# ---- google_sql_database / google_sql_user / variable ------------------------------


def _generate_database(file: HclFile, names: _Names, instance: DatabaseInstance) -> None:
    label, _, _ = names.allocate("google_sql_database", instance.id)
    block = file.block("resource", "google_sql_database", label)
    block.attr("name", instance.initial_database)
    block.attr("instance", Ref(f"google_sql_database_instance.{names.label[instance.id]}.name"))


def _generate_user(
    file: HclFile, names: _Names, instance: DatabaseInstance, password_vars: dict[str, str]
) -> None:
    label, _, _ = names.allocate("google_sql_user", instance.id)
    username = instance.master_username or _DEFAULT_USERNAME[instance.engine]
    block = file.block("resource", "google_sql_user", label)
    block.attr("name", username)
    block.attr("instance", Ref(f"google_sql_database_instance.{names.label[instance.id]}.name"))
    block.attr("password", Ref(f"var.{password_vars[instance.id]}"))


def _generate_password_variable(file: HclFile, variable_name: str) -> None:
    block = file.block("variable", variable_name)
    block.comment("no default: easymigrate plan writes secrets.auto.tfvars.json")
    block.attr("type", Ref("string"))
    block.attr("sensitive", True)


